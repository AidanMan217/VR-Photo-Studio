"""Generate the Windows version resource for the VR Photo Studio executables.

The version comes from ``vrphoto.__version__`` (parsed from ``src/vrphoto/__init__.py``),
so bumping the package version is all a release needs.  ``vrphoto.spec`` calls
:func:`write_version_file` once per executable; it can also be run by hand::

    python packaging/version_info.py OUT.txt [--exe VRPhotoStudio.exe] [--description "..."]

The output is PyInstaller's text form of ``VSVersionInfo`` (``eval``-able by
``PyInstaller.utils.win32.versioninfo.load_version_info_from_text_file``).
"""

from __future__ import annotations

import argparse
import datetime as _dt
import sys
from collections.abc import Sequence
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import spec_helpers as H  # noqa: E402  (needs the sys.path tweak above)

_TEMPLATE = """# UTF-8
# Generated by packaging/version_info.py - do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={filevers!r},
    prodvers={filevers!r},
    mask=0x3f,
    flags={flags},
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [{strings}])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def version_strings(
    version: str,
    *,
    exe_name: str,
    description: str,
    year: int | None = None,
) -> dict[str, str]:
    """The ``StringFileInfo`` entries shown in Explorer's Properties -> Details tab."""
    year = year or _dt.date.today().year
    return {
        "CompanyName": H.PUBLISHER,
        "FileDescription": description,
        "FileVersion": version,
        "InternalName": Path(exe_name).stem,
        "LegalCopyright": f"Copyright (c) 2026-{year} {H.PUBLISHER}. MIT License."
        if year > 2026
        else f"Copyright (c) 2026 {H.PUBLISHER}. MIT License.",
        "OriginalFilename": exe_name,
        "ProductName": H.APP_NAME,
        "ProductVersion": version,
    }


def render_version_info(
    version: str,
    *,
    exe_name: str = f"{H.GUI_EXE}.exe",
    description: str = H.APP_NAME,
    year: int | None = None,
) -> str:
    """Return the version-resource text for one executable."""
    filevers = H.version_tuple(version)
    # VS_FF_PRERELEASE (0x2) for anything that is not a plain N.N.N release
    plain = version.strip().lstrip("v").replace(".", "").isdigit()
    flags = "0x0" if plain else "0x2"
    strings = version_strings(version, exe_name=exe_name, description=description, year=year)
    body = ",\n         ".join(f"StringStruct({k!r}, {v!r})" for k, v in strings.items())
    return _TEMPLATE.format(filevers=filevers, flags=flags, strings=body)


def write_version_file(
    path: Path,
    version: str | None = None,
    *,
    exe_name: str = f"{H.GUI_EXE}.exe",
    description: str = H.APP_NAME,
) -> Path:
    """Write the version resource file for ``exe_name`` and return its path."""
    version = version or H.read_version()
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        render_version_info(version, exe_name=exe_name, description=description), encoding="utf-8"
    )
    return path


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("out", type=Path, help="output text file")
    ap.add_argument("--exe", default=f"{H.GUI_EXE}.exe", help="executable file name")
    ap.add_argument("--description", default=H.APP_NAME, help="FileDescription string")
    ap.add_argument("--version", default=None, help="override the version (default: vrphoto.__version__)")
    args = ap.parse_args(argv)
    p = write_version_file(args.out, args.version, exe_name=args.exe, description=args.description)
    sys.stdout.write(f"wrote {p}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
